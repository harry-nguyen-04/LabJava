CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(32)    NOT NULL,
    customer_id      BIGINT         NOT NULL,
    customer_name    VARCHAR(255)   NOT NULL,
    created_by       BIGINT         NOT NULL,
    status           VARCHAR(32)    NOT NULL,
    discount_percent NUMERIC(5, 2)  NOT NULL,
    tax_percent      NUMERIC(5, 2)  NOT NULL,
    currency         VARCHAR(3)     NOT NULL,
    created_at       TIMESTAMPTZ    NOT NULL,
    updated_at       TIMESTAMPTZ    NOT NULL,
    paid_at          TIMESTAMPTZ,
    fulfilled_at     TIMESTAMPTZ,
    cancelled_at     TIMESTAMPTZ,
    CONSTRAINT uq_orders_code UNIQUE (code),
    CONSTRAINT ck_orders_status CHECK (status IN ('DRAFT', 'PENDING_PAYMENT', 'PAID', 'FULFILLED', 'CANCELLED'))
);

CREATE TABLE order_lines (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT       NOT NULL,
    line_no      INTEGER      NOT NULL,
    product_id   BIGINT       NOT NULL,
    sku          VARCHAR(64)  NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    quantity     INTEGER      NOT NULL,
    unit_price   BIGINT       NOT NULL,
    CONSTRAINT fk_order_lines_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT uq_order_lines_order_line_no UNIQUE (order_id, line_no),
    CONSTRAINT ck_order_lines_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_order_lines_order_id ON order_lines (order_id);
